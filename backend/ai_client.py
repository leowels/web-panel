async def get_ai_settings_from_db(db) -> Optional[dict]:
    """Р В РЎСџР В РЎвЂўР В Р’В»Р РЋРЎвЂњР РЋРІР‚РЋР В РЎвЂР РЋРІР‚С™Р РЋР Р‰ Р В Р вЂ¦Р В Р’В°Р РЋР С“Р РЋРІР‚С™Р РЋР вЂљР В РЎвЂўР В РІвЂћвЂ“Р В РЎвЂќР В РЎвЂ AI Р В РЎвЂР В Р’В· Р В Р’В±Р В Р’В°Р В Р’В·Р РЋРІР‚в„– Р В РўвЂР В Р’В°Р В Р вЂ¦Р В Р вЂ¦Р РЋРІР‚в„–Р РЋРІР‚В¦"""
    try:
        from sqlalchemy import select
        try:
            from backend.models import SystemSettings
        except ImportError:
            from models import SystemSettings
        
        result = await db.execute(
            select(SystemSettings).where(
                SystemSettings.key.in_([
                    "ai_provider",
                    "ai_api_key",
                    "ai_base_url",
                    "ai_model",
                    "ai_agent_access_id"  # Р В РІР‚СњР В Р’В»Р РЋР РЏ Timeweb Cloud Р В Р’В°Р В РЎвЂ“Р В Р’ВµР В Р вЂ¦Р РЋРІР‚С™Р В РЎвЂўР В Р вЂ 
                ])
            )
        )
        settings = result.scalars().all()
        
        settings_dict = {}
        for setting in settings:
            settings_dict[setting.key] = setting.value
        
        return settings_dict if settings_dict else None
    except Exception as e:
        print(f"Error loading AI settings from DB: {e}")
        return None

